export type Difficulty = "foundation" | "core" | "stretch";

export type Topic =
  | "PinYin"
  | "BianZi"
  | "CiYu"
  | "KanTu"
  | "PeiDui"
  | "TianKong"
  | "ZuJu"
  | "YueReadMCQ"
  | "YueReadOpen"
  | "JuZi";

export interface SolutionInfo {
  /** 해결 방법 / 풀이 방법 */
  method: string;
  /** 단계별 풀이 과정 */
  steps: string[];
  /** 학습 팁 */
  tip: string;
}

/** Type A: 단일 문제 (PinYin, BianZi, CiYu, JuZi, ZuJu 등) */
export interface SingleQuestion {
  id: string;
  topic: Topic;
  difficulty: Difficulty;
  instruction: string;
  q: string;
  /** 객관식일 때만 사용. 주관식(JuZi, ZuJu 등)은 생략 */
  options?: string[];
  /** MCQ: 0-based index (number) | OpenEnded: 정답/모범 텍스트 (string) */
  answer: string | number;
  pinyin: string;
  meaning: string;
  solution: SolutionInfo;
}

/** Type B 의 세트 내부 개별 질문 */
export interface SubQuestion {
  id: string;
  type: "MCQ" | "OpenEnded";
  q: string;
  options?: string[];
  /** MCQ: 0-based index (number) | OpenEnded: 정답 텍스트 (string) */
  answer: string | number;
  pinyin: string;
  meaning: string;
  solution: SolutionInfo;
}

/** Type B: 세트/지문 문제 (PeiDui, TianKong, JuZi(组句成段), YueReadMCQ, YueReadOpen 등) */
export interface SetQuestion {
  id: string;
  topic: Topic;
  difficulty: Difficulty;
  setLabel: string;
  instruction?: string;
  passage?: string;
  /** 제시어 단어 표 (词语表) - 있을 때만 사용 */
  wordBank?: string[];
  questions: SubQuestion[];
}

export type PaperQuestion = SingleQuestion | SetQuestion;

