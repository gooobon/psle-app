/* ---------- converter helpers (identical to verify_mapping) ---------- */
function wordBankArray(wb) { return Array.isArray(wb) ? wb.slice() : Object.values(wb || {}); }
function normWord(answer, wb) {
  if (typeof answer === 'string' && wb && !Array.isArray(wb)
      && Object.prototype.hasOwnProperty.call(wb, answer.trim())) return wb[answer.trim()];
  return answer;
}
function sentenceContaining(passage, word) {
  if (!word) return '';
  const parts = String(passage).split(/(?<=[.!?])\s+/);
  return parts.find(p => p.includes(word)) || '';
}

/* ---------- per-set converter -> { type -> PlanSection } ---------- */
function convertSet(setId) {
  const raw = setsById[setId], S = raw.sections, out = {};
  for (const [key, type] of [['A', 'VocabMCQ'], ['B', 'GrammarMCQ']]) {
    const sec = S[key];
    const items = sec.questions.map((q, i) => ({
      id: `${setId}_${key}_${q.question_id ?? i}`,
      topic: type,
      sentence: q.stem,
      options: Object.values(q.options),
      answer: parseInt(q.answer, 10) - 1,
      explanation: q.learning_tip,
    }));
    out[type] = { type, items, marks: items.length };
  }
  for (const [key, type] of [['C', 'GrammarCloze'], ['D', 'VocabCloze']]) {
    const sec = S[key];
    const set = {
      id: `${setId}_${key}`,
      passage: sec.passage,
      wordBank: wordBankArray(sec.word_box),
      blanks: sec.questions.map(q => ({ num: q.blank_number, answer: normWord(q.answer, sec.word_box), hint: q.trap_type, explanation: q.learning_tip })),
    };
    out[type] = { type, items: [set], marks: set.blanks.length };
  }
  {
    const sec = S.E, cont = sec.errors || sec.questions || [];
    const items = cont.map(it => {
      const wrong = it.wrong_word || it.error_word;
      return {
        id: `${setId}_E_${it.question_id ?? it.blank_number}`,
        answer: it.correction,
        questionNumber: it.blank_number,
        wrongWord: wrong,
        sentence: sentenceContaining(sec.passage, wrong),
      };
    });
    out.Editing = { type: 'Editing', items: [{ id: `${setId}_E`, items }], marks: items.length };
  }
  {
    const sec = S.F || S.f, fqs = (sec && sec.questions) || [];
    const items = fqs.map((q, i) => ({
      id: `${setId}_F${i + 1}`,
      sentenceA: q.sentence1 != null ? q.sentence1 : q.sentence_a,
      sentenceB: (q.sentence2 != null ? q.sentence2 : q.sentence_b) || undefined,
      starter: q.starter || undefined,
      instruction: q.instruction,
      answer: q.model_answer,
      answerSimple: q.model_answer_simple || undefined,
      hint: q.trap_type,
      explanation: q.learning_tip,
      marks: q.marks || 2,
    }));
    out.Synthesis = { type: 'Synthesis', items, marks: items.reduce((a, q) => a + (q.marks || 0), 0) };
  }
  {
    const c = COMP[setId], qs = c.generated.questions;
    const marks = qs.reduce((a, q) => a + (q.marks || 1), 0);
    out.Comprehension = { type: 'Comprehension', items: [{ id: `${setId}_G`, passage: c.passage, questions: qs }], marks };
  }
  return out;
}

/* ---------- build PracticeSet[] (plan ordered by SECTION_ORDER) ---------- */
const practiceSets = WA1.sets.map(raw => {
  const byType = convertSet(raw.set_id);
  return { setId: raw.set_id, theme: raw.theme, plan: SECTION_ORDER.map(t => byType[t]) };
});

