const norm = s => String(s || '').trim().toLowerCase().replace(/[.,!?'"]/g, '');
function correctIdxForMcq(q) {
  const opts = (q.options || []).map(o => typeof o === 'string' ? o : String(o.text || o));
  const a = q.answer;
  if (typeof a === 'number') return a;
  if (typeof a === 'string') { const li = a.toUpperCase().charCodeAt(0) - 65; if (li >= 0 && li < opts.length) return li; const n = parseInt(a, 10); if (!isNaN(n)) return n >= 1 ? n - 1 : n; }
  return 0;
}
