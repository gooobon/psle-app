    T(Array.isArray(q.options) && q.options.length === 4 && q.options.every(o => typeof o === 'string'), `${q.id}: options bad`);
    T(Number.isInteger(q.answer) && q.answer >= 0 && q.answer < 4, `${q.id}: answer idx bad`);
