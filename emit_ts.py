#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Re-emit src/data/p3/chinese/wa1_practice.ts from wa1_zh_complete.json (Part B).
Preserves exact header/import/marker/footer format. Real UTF-8 Chinese, no BOM."""
import json, os, re
HERE = os.path.dirname(__file__)
_TAX = json.load(open(os.path.join(HERE, "src", "data", "taxonomy", "taxonomy.json"), encoding="utf-8"))
_ZH_SKILL = _TAX["zhSkillToConcept"]
_ZH_LOOKALIKE = set(_TAX["zhLookalikeSkills"])
_NEG_RE = re.compile(r"哪[一个项].{0,16}不|不正确的是|哪一项不是|哪一个不是")

def apply_zh_taxonomy(node):
    """Add optional conceptIds/trapIds from the existing skill field. Does not edit stems or answers."""
    if isinstance(node, list):
        for item in node:
            apply_zh_taxonomy(item)
        return
    if not isinstance(node, dict):
        return
    skill = node.get("skill")
    if isinstance(skill, str) and skill in _ZH_SKILL and "conceptIds" not in node:
        node["conceptIds"] = [_ZH_SKILL[skill]]
        node["taxonomyStatus"] = "certain"
        if skill in _ZH_LOOKALIKE:
            node["trapIds"] = ["trap.lookalike"]
    text = " ".join(
        node.get(key) for key in ("sentence", "stem", "q", "question", "instruction")
        if isinstance(node.get(key), str)
    )
    is_item = ("answer" in node) or isinstance(skill, str)
    if is_item and text and _NEG_RE.search(text):
        traps = node.setdefault("trapIds", [])
        if "trap.negation" not in traps:
            traps.append("trap.negation")
    if is_item and node.get("format") == "sequence":
        traps = node.setdefault("trapIds", [])
        if "trap.sequence_order" not in traps:
            traps.append("trap.sequence_order")
    for value in list(node.values()):
        apply_zh_taxonomy(value)

data = json.load(open(os.path.join(HERE, "wa1_zh_complete.json"), encoding="utf-8"))
apply_zh_taxonomy(data)
# which sets are enriched (have any explanation_en)
def enriched(z):
    found = [False]
    def walk(o):
        if isinstance(o, list):
            for x in o: walk(x)
        elif isinstance(o, dict):
            if "explanation_en" in o: found[0] = True
            for v in o.values(): walk(v)
    walk(z["plan"])
    return found[0]
done = [z["setId"] for z in data if enriched(z)]
rng = f"{done[0]}-{done[-1]}" if done else "none"
header = (f"// wa1_practice.ts (GENERATED) - enriched sets: {len(done)}/60 ({','.join(done)}); "
          f"remaining pending full expansion\n"
          'import type { ZhPracticeSet } from "./schema";\n\n'
          "export const WA1_ZH_PRACTICE: ZhPracticeSet[] =\n"
          "/* WA1_ZH_JSON_BEGIN */\n")
body = json.dumps(data, ensure_ascii=False, indent=1)
footer = "\n/* WA1_ZH_JSON_END */\n;\n\nexport default WA1_ZH_PRACTICE;\n"
out = header + body + footer
with open(os.path.join(HERE, "src", "data", "p3", "chinese", "wa1_practice.ts"), "w", encoding="utf-8") as f:
    f.write(out)
# round-trip check
begin = out.index("/* WA1_ZH_JSON_BEGIN */") + len("/* WA1_ZH_JSON_BEGIN */\n")
end = out.index("\n/* WA1_ZH_JSON_END */")
parsed = json.loads(out[begin:end])
assert len(parsed) == 60, f"round-trip set count {len(parsed)}"
print(f"emitted wa1_practice.ts  sets=60  enriched={len(done)} ({rng})  round-trip OK")
# STEP10_DRILL: emit drill-only sets (generated, validated, human-reviewed) as a separate TS module
drill_path = os.path.join(HERE, "wa1_zh_drill.json")
drill = json.load(open(drill_path, encoding="utf-8")) if os.path.exists(drill_path) else []
apply_zh_taxonomy(drill)
with open(os.path.join(HERE, "src", "data", "p3", "chinese", "wa1_drill.ts"), "w", encoding="utf-8") as f:
    f.write("// wa1_drill.ts (GENERATED by emit_ts.py) - drill-only sets from wa1_zh_drill.json; never merged into WA1_ZH_PRACTICE\n"
            'import type { ZhPracticeSet } from "./schema";\n\n'
            "export const WA1_ZH_DRILL: ZhPracticeSet[] =\n/* WA1_ZH_DRILL_JSON_BEGIN */\n" + json.dumps(drill, ensure_ascii=False, indent=1)
            + "\n/* WA1_ZH_DRILL_JSON_END */\n;\n\nexport default WA1_ZH_DRILL;\n")
print(f"emitted wa1_drill.ts  sets={len(drill)}")
# STEP5_BANK: rebuild the skill item bank whenever the data is re-emitted
import importlib.util as _ilu
_spec = _ilu.spec_from_file_location("build_zh_bank", os.path.join(HERE, "tools", "bank", "build_zh_bank.py"))
_m = _ilu.module_from_spec(_spec); _spec.loader.exec_module(_m); _m.main()
