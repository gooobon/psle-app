// Audit: English cloze / grammar / editing items whose explanation contradicts the keyed answer.
// Read-only. Usage: node tools/cloze_explanation_audit.mjs   (writes docs/audits/cloze_explanations.md)
// Reads the generated data module src/data/p3/english/wa1_practice.ts (a JSON array literal). Fixes belong in the source
// (20260622_WA1_complete.json), then `node build_wa1_practice.js`. Answers are never edited by this tool.
import fs from 'node:fs';

const SRC = 'src/data/p3/english/wa1_practice.ts';
const OUT = 'docs/audits/cloze_explanations.md';
const text = fs.readFileSync(SRC, 'utf8');
const start = text.indexOf('WA1_PRACTICE_SETS');
const open = text.indexOf('[', text.indexOf('=', start));
const close = text.lastIndexOf('];');
const sets = JSON.parse(text.slice(open, close + 1));

const PRON = new Set(['i', 'me', 'my', 'mine', 'we', 'us', 'our', 'ours', 'you', 'your', 'he', 'him', 'his', 'she', 'her', 'hers', 'it', 'its', 'they', 'them', 'their', 'theirs']);
const GENDER = { he: 'm', him: 'm', his: 'm', she: 'f', her: 'f', hers: 'f' };
const PAST = new Set(['was', 'were', 'did', 'had']);
const PRESENT = new Set(['is', 'are', 'am', 'do', 'does', 'has', 'have']);
const FUTURE = new Set(['will', 'shall']);

const tokens = (s) => (String(s).toLowerCase().match(/[a-z']+/g) || []);

function check(answer, expl) {
  const ans = String(answer || '').trim().toLowerCase();
  if (!ans || !expl) return null;
  const toks = tokens(expl);
  // 1. pronoun answer, explanation only talks about other pronouns
  if (PRON.has(ans)) {
    const mentioned = toks.filter((t) => PRON.has(t));
    if (mentioned.length && !mentioned.includes(ans)) return `answer pronoun "${ans}" not mentioned; explanation names ${[...new Set(mentioned)].join(', ')}`;
    const g = GENDER[ans];
    if (g) {
      const other = mentioned.filter((t) => GENDER[t] && GENDER[t] !== g);
      const same = mentioned.filter((t) => GENDER[t] === g);
      if (other.length && !same.length) return `answer is ${g === 'm' ? 'male' : 'female'} ("${ans}") but explanation refers to ${[...new Set(other)].join(', ')}`;
    }
  }
  // 2. tense auxiliary answer vs tense named in explanation
  const named = [];
  if (/\bpast\b/i.test(expl)) named.push('past');
  if (/\bpresent\b/i.test(expl)) named.push('present');
  if (/\bfuture\b/i.test(expl)) named.push('future');
  const kind = PAST.has(ans) ? 'past' : PRESENT.has(ans) ? 'present' : FUTURE.has(ans) ? 'future' : null;
  if (kind && named.length === 1 && named[0] !== kind) return `answer "${ans}" is ${kind} tense but explanation names ${named[0]} tense`;
  // 3. explanation quotes/CAPS a single word that is not the answer (only when it names no tokens equal to the answer)
  const quoted = [...String(expl).matchAll(/'([A-Za-z]+)'|\b([A-Z]{2,})\b/g)].map((m) => (m[1] || m[2]).toLowerCase());
  if (/^[a-z]+$/.test(ans) && quoted.length === 1 && !toks.includes(ans) && !quoted.includes(ans) && quoted.every((q) => !['a', 'an', 'the'].includes(q)) && quoted.length <= 2 && quoted.every((q) => q.length > 1 && /^[a-z]+$/.test(q) && !/^[a-e]$/.test(q))) {
    const stop = new Set(['mcq', 'nb', 'sv', 'vs', 'eg', 'ie']);
    const real = quoted.filter((q) => !stop.has(q));
    if (real.length && !real.includes(ans) && !toks.some((t) => t.startsWith(ans)) && !ans.startsWith(real[0].replace(/e$/, ''))) return `explanation quotes ${real.map((q) => `"${q}"`).join(', ')} but the answer is "${ans}"`;
  }
  return null;
}

const rows = [];
let n = 0;
for (const set of sets) {
  for (const sec of set.plan || []) {
    for (const it of sec.items || []) {
      // cloze set: blanks[] with string answers
      for (const b of it.blanks || []) {
        n++;
        const why = check(b.answer, b.explanation);
        if (why) rows.push({ id: `${set.setId}/${sec.type}/${it.id}_${b.num}`, answer: b.answer, snippet: b.explanation, why });
      }
      // MCQ: options[answer]
      if (Array.isArray(it.options) && typeof it.answer === 'number') {
        n++;
        const why = check(it.options[it.answer], it.explanation);
        if (why) rows.push({ id: `${set.setId}/${sec.type}/${it.id}`, answer: it.options[it.answer], snippet: it.explanation, why });
      }
      // Editing: single-word corrections
      if (sec.type === 'Editing' && typeof it.answer === 'string') {
        n++;
        const why = check(it.answer, it.explanation);
        if (why) rows.push({ id: `${set.setId}/${sec.type}/${it.id}`, answer: it.answer, snippet: it.explanation, why });
      }
    }
  }
}

const esc = (s) => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ').slice(0, 220);
const md = ['# English cloze / grammar explanation audit', '',
  `Generated by \`tools/cloze_explanation_audit.mjs\` from \`${SRC}\`. Items checked: ${n}. Flagged: ${rows.length}.`,
  'Checks: pronoun answer vs pronouns named in the explanation (incl. gender), tense auxiliary vs tense named, and a single quoted / CAPS word that differs from the answer.',
  'Answers are never changed; fix explanation wording in `20260622_WA1_complete.json` and rerun `node build_wa1_practice.js`.', '',
  '| Item id | Answer | Explanation snippet | Reason |', '|---|---|---|---|',
  ...rows.map((r) => `| ${r.id} | ${esc(r.answer)} | ${esc(r.snippet)} | ${esc(r.why)} |`), ''].join('\n');
fs.mkdirSync('docs/audits', { recursive: true });
fs.writeFileSync(OUT, md);
console.log(`checked ${n}, flagged ${rows.length} -> ${OUT}`);
